// lib/library-articles.ts
// Single source of truth for full library articles (long-form content with dedicated pages).
// Each article renders at /library/[slug] via app/library/[slug]/page.tsx
// and also appears as a card on /library via app/library/page.tsx (ITEMS array).

export interface LibrarySection {
  heading: string;
  /** Paragraphs may include simple inline HTML: <strong>, <em>, and <a href="..."> for internal links. */
  body: string[];
  /** Optional bullet or numbered list rendered after body paragraphs. */
  list?: string[];
  listType?: "bullet" | "number";
}

export interface LibraryArticle {
  slug: string;
  /** H1 */
  title: string;
  /** Subtitle line shown under the H1 */
  kicker: string;
  /** SEO */
  seoTitle: string;
  seoDescription: string;
  seoKeywords: string[];
  /** Maya's content taxonomy */
  mainCategory: string;
  subcategories: string[];
  tags: string[];
  /** Alt text for the main image, ready for whenever a hero image is added */
  heroImageAlt: string;
  /** SiteIcon name for the hero category badge (defaults to "clock") */
  icon?: string;
  /** Suggested opening line for social sharing */
  shareSentence: string;
  /** Opening paragraphs before the first H2 */
  intro: string[];
  sections: LibrarySection[];
  /** Optional heading override for the reflection-questions box (defaults to "שאלות להתבוננות") */
  reflectionHeading?: string;
  reflectionQuestions: string[];
  summary: string[];
  /** Related tool slugs from lib/tools-data.ts, shown as a "related tools" grid at the bottom */
  relatedToolSlugs: string[];
}

